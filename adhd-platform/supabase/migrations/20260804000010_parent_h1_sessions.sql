-- ============================================================================
-- 親職諮詢上半年場次補建（2026-08-04 Phase 2）
--
-- 背景：與導航計畫（20260804000009）同一個問題——親職諮詢 4～6 月的場次實際上
--   已經辦過，但從來只存在於前台手寫的活動卡與服務頁的一段固定文字裡，資料庫
--   沒有對應的列。手寫卡已隨 Phase 2 移除、服務頁的「上半年度開放場次」固定文字
--   也已改為讀資料庫，因此若不補建，這段歷史就會消失、活動軌跡也是空的。
--
-- 資料來源：站上原本公開的 8 張場次卡（【ADHD 家長諮詢服務】四月場一…六月場三）。
--   時段沿用 H2 場次的模型：每個時段各 1 名額。booked_count 一律 0——這是補建的
--   歷史紀錄，不是報名資料。
--
-- ⚠ 來源不一致（需人工確認）：服務頁的固定文字寫「【四月場次】4/18：10:00-11:00 /
--   11:00-12:00」，每月只列 2 個時段；但場次卡在五月與六月各有 3 張，多出
--   09:00-10:00 一場。本檔採用較具體的場次卡（共 8 場）。若正確答案是每月 2 場，
--   請刪掉 5/23 與 6/6 的 09:00 兩列後再套用。
--
-- 不刪除任何資料。冪等：可重複執行。
-- ============================================================================

insert into public.sessions (project_id, title, starts_at, ends_at, capacity, booked_count, status, admin_note)
select p.id, v.title, v.starts_at, v.ends_at, 1, 0, 'done',
       '2026-08-04 補建：本場實際已辦理，原本只存在於前台手寫場次卡，補進資料庫供活動軌跡顯示。'
from public.projects p
cross join (values
  ('【ADHD 家長諮詢服務】免費公益線上諮詢 (四月場一)', timestamptz '2026-04-18 10:00+08', timestamptz '2026-04-18 11:00+08'),
  ('【ADHD 家長諮詢服務】免費公益線上諮詢 (四月場二)', timestamptz '2026-04-18 11:00+08', timestamptz '2026-04-18 12:00+08'),
  ('【ADHD 家長諮詢服務】免費公益線上諮詢 (五月場一)', timestamptz '2026-05-23 09:00+08', timestamptz '2026-05-23 10:00+08'),
  ('【ADHD 家長諮詢服務】免費公益線上諮詢 (五月場二)', timestamptz '2026-05-23 10:00+08', timestamptz '2026-05-23 11:00+08'),
  ('【ADHD 家長諮詢服務】免費公益線上諮詢 (五月場三)', timestamptz '2026-05-23 11:00+08', timestamptz '2026-05-23 12:00+08'),
  ('【ADHD 家長諮詢服務】免費公益線上諮詢 (六月場一)', timestamptz '2026-06-06 09:00+08', timestamptz '2026-06-06 10:00+08'),
  ('【ADHD 家長諮詢服務】免費公益線上諮詢 (六月場二)', timestamptz '2026-06-06 10:00+08', timestamptz '2026-06-06 11:00+08'),
  ('【ADHD 家長諮詢服務】免費公益線上諮詢 (六月場三)', timestamptz '2026-06-06 11:00+08', timestamptz '2026-06-06 12:00+08')
) as v(title, starts_at, ends_at)
where p.slug = 'parent'
  and not exists (
    select 1 from public.sessions s
    where s.project_id = p.id and s.starts_at = v.starts_at and s.ends_at = v.ends_at
  );
