-- ----------------------------------------------------------------------------
-- 1. 刪掉 E2E 測試場次
--
-- `【測試】E2E 專用場次（勿用，測完刪除）`，2026-08-01、容量 5、closed。
-- 它只是因為日期過了才沒出現在前台，不是因為被下架——哪天有人把日期改到未來，
-- 它就會出現在家長眼前。
--
-- **只刪沒有任何報名指向它的**：`registrations.session_ids` 是 uuid[]，沒有外鍵，
-- 刪掉被引用的場次會在報名紀錄裡留下指不到東西的 id。條件寫在 SQL 裡而不是靠
-- 執行前目測，這樣重跑也安全。
--
-- 同一批查到的另一筆 `【測試】7月18日創作聚會（Vtuber 殷緋）` **刻意不刪**：
-- 它 booked_count = 2、掛著真實報名紀錄，狀態已是 cancelled 且日期已過，
-- 前台兩邊都不會出現（軌跡只收 done），留著無害、刪掉會弄壞報名紀錄。
-- ----------------------------------------------------------------------------
delete from public.sessions s
where s.title = '【測試】E2E 專用場次（勿用，測完刪除）'
  and s.booked_count = 0
  and not exists (
    select 1 from public.registrations r
    where s.id = any(coalesce(r.session_ids, '{}'))
  );

