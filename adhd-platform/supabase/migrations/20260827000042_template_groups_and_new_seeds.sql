declare
  aligned integer;
begin
  update public.email_templates as t
     set project_id = p.id
    from (values
      ('確認信・親職版', 'parent'),
      ('確認信・導航版', 'navigator'),
      ('家長行前信',     'parent')
    ) as v(name, slug)
    join public.projects p on p.slug = v.slug
   where t.name = v.name
     and t.project_id is distinct from p.id;

  select count(*) into aligned
    from public.email_templates t
    join (values
      ('確認信・親職版', 'parent'),
      ('確認信・導航版', 'navigator'),
      ('家長行前信',     'parent')
    ) as v(name, slug) on v.name = t.name
    join public.projects p on p.slug = v.slug and p.id = t.project_id;

  if aligned <> 3 then
    raise exception '回填後只有 % 封範本對齊服務線，預期 3 封——名稱或 slug 對不上，全數回滾', aligned;
  end if;
end $$;

