-- 消失，比留在通用組更難發現。
--
-- 冪等：UPDATE 帶 `is distinct from` 所以重跑不會產生第二筆稽核紀錄（019 的 trigger 對
-- 無異動的更新本來就不寫 audit_log，但少一次無謂的寫入還是比較乾淨）。
-- 檢查的不是「這次改了幾列」而是「現在對齊了幾列」——改了幾列在重跑時會是 0，
-- 對齊了幾列在重跑時仍然是 3。這樣才同時擋得住「名稱對不上」又不會讓重跑炸掉。
-- ---------------------------------------------------------------------------
