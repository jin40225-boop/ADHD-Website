-- 收信範圍的第二個維度：時間。
--
-- 原本的規則只回答「誰的信要收」，沒有回答「什麼時候的信要收」，所以規則一開，
-- 每個人從古至今的往來就整批被拉進來（量體 444 封）。舊信大多早就處理完了，
-- 進來只會混淆視聽——但家長與諮詢者的通聯有留存價值，需要時要拿得到。
--
-- 原則：**自動發現受起始日限制，人工指定不受限制。**
--   * 自動搜尋（已知信箱、主旨關鍵字）一律帶 Gmail 的 `after:`
--   * 貼標籤的信不受限制——貼標籤本身就是「我要這封」的明確指定
--   * 「匯入這個人的歷史往來」不受限制——同上，而且是逐人決定的
--
-- 預設值是套用當天：套用之後才進來的信才會自動收，之前的一律不動。
-- null＝不限制（想回到舊行為時把它清空即可，但那會讓每個人的全部歷史再次湧入）。
alter table public.app_settings
  add column if not exists sync_since date default current_date;

comment on column public.app_settings.sync_since is
  'gmail-sync 自動發現的起始日：只找這天之後的信。標籤查詢與「匯入這個人的歷史往來」不受此限制。null＝不限制。';
